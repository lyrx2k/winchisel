fn app_ext(
    lang: Language,
    name: &str,
    cat: DownloadCategory,
    winget_ids: Vec<String>,
    website_url: &str,
) -> DownloadApp {
    let winget_ids_lc: Vec<String> = winget_ids.iter().map(|s| s.to_ascii_lowercase()).collect();
    DownloadApp {
        name: name.to_string(),
        name_lc: name.to_ascii_lowercase(),
        description: t(lang, name).to_string(),
        description_lc: format!(
            "{} {}",
            t(Language::English, name).to_ascii_lowercase(),
            t(Language::German, name).to_ascii_lowercase()
        ),
        category: cat,
        winget_ids,
        winget_ids_lc,
        website_url: website_url.to_string(),
        website_url_lc: website_url.to_ascii_lowercase(),
    }
}
